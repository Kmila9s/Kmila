using System.Text.Json.Serialization;

namespace Kmila.Shared.Models;

/// <summary>
/// Represents the clocking resource specifications of an FPGA device.
/// Clocking resources are essential for generating and distributing clock signals
/// throughout the FPGA fabric.
/// </summary>
/// <remarks>
/// Different FPGA families have varying clocking architectures:
/// - Xilinx uses DCMs (Digital Clock Managers) and MMCMs (Mixed-Mode Clock Managers)
/// - Altera/Intel uses PLLs (Phase-Locked Loops)
/// - Lattice uses PLLs and dedicated clock networks
/// </remarks>
public class FPGAClocking
{
    /// <summary>
    /// Gets or sets the number of PLL (Phase-Locked Loop) units available.
    /// </summary>
    /// <remarks>
    /// PLLs are used to generate multiple clock frequencies from a single reference clock,
    /// perform clock multiplication/division, and phase shifting.
    /// </remarks>
    [JsonPropertyName("pll_count")]
    public int? PllCount { get; set; }

    /// <summary>
    /// Gets or sets the number of DCM/MMCM (Digital Clock Manager / Mixed-Mode Clock Manager) units available.
    /// </summary>
    /// <remarks>
    /// DCMs and MMCMs provide advanced clock management features including
    /// frequency synthesis, phase shifting, and duty cycle correction.
    /// Primarily found in Xilinx FPGAs.
    /// </remarks>
    [JsonPropertyName("dcm_mmcm_count")]
    public int? DcmMmcmCount { get; set; }

    /// <summary>
    /// Gets or sets the maximum PLL output frequency in MHz.
    /// </summary>
    /// <remarks>
    /// This represents the highest frequency that can be generated by the FPGA's
    /// clock management resources. Actual achievable frequencies depend on the
    /// specific design and timing constraints.
    /// </remarks>
    [JsonPropertyName("max_pll_output_mhz")]
    public int? MaxPllOutputMhz { get; set; }
}
