using System.Text.Json.Serialization;

namespace Kmila.Shared.Models;

/// <summary>
/// Represents the clocking resource specifications of an FPGA device.
/// Clocking resources are essential for generating and distributing clock signals
/// throughout the FPGA fabric.
/// </summary>
/// <remarks>
/// Different FPGA families have varying clocking architectures:
/// - Xilinx uses DCMs (Digital Clock Managers) and MMCMs (Mixed-Mode Clock Managers)
/// - Altera/Intel uses PLLs (Phase-Locked Loops)
/// - Lattice uses PLLs and dedicated clock networks
/// </remarks>
public class FPGAClocking
{
    /// <summary>
    /// Gets or sets the number of PLL (Phase-Locked Loop) units available.
    /// </summary>
    /// <remarks>
    /// PLLs are used to generate multiple clock frequencies from a single reference clock,
    /// perform clock multiplication/division, and phase shifting.
    /// </remarks>
    [JsonPropertyName("pll_count")]
    public int? PllCount { get; set; }

    /// <summary>
    /// Gets or sets the number of DCM/MMCM (Digital Clock Manager / Mixed-Mode Clock Manager) units available.
    /// </summary>
    /// <remarks>
    /// DCMs and MMCMs provide advanced clock management features including
    /// frequency synthesis, phase shifting, and duty cycle correction.
    /// Primarily found in Xilinx FPGAs.
    /// </remarks>
    [JsonPropertyName("dcm_mmcm_count")]
    public int? DcmMmcmCount { get; set; }

    /// <summary>
    /// Gets or sets the maximum PLL output frequency in MHz.
    /// </summary>
    /// <remarks>
    /// This represents the highest frequency that can be generated by the FPGA's
    /// clock management resources. Actual achievable frequencies depend on the
    /// specific design and timing constraints.
    /// </remarks>
    [JsonPropertyName("max_pll_output_mhz")]
    public int? MaxPllOutputMhz { get; set; }

    /// <summary>
    /// Optional override for the default simulation system clock in MHz.
    /// When present, Kmila uses this directly as the simulator's tick rate.
    /// When absent, the app derives a sensible default from
    /// <see cref="MaxPllOutputMhz"/> (see <see cref="GetDefaultSimClockMhz"/>).
    /// Kept optional so existing bundled JSON files don't need migration —
    /// curriculum authors can opt-in per device.
    /// </summary>
    [JsonPropertyName("system_clock_mhz")]
    public int? SystemClockMhz { get; set; }

    /// <summary>
    /// Effective default system-clock frequency (MHz) used by the simulator
    /// when the student hasn't set a per-project override.
    /// </summary>
    /// <remarks>
    /// Priority: explicit <see cref="SystemClockMhz"/> &gt; <see cref="MaxPllOutputMhz"/>
    /// heuristic &gt; fallback 50 MHz. The PLL-based heuristic caps the clock
    /// at 100 MHz so a device advertising 1300 MHz PLL output doesn't push
    /// the simulator into millions-of-ticks territory for a 1 µs run.
    /// </remarks>
    public int GetDefaultSimClockMhz()
    {
        if (SystemClockMhz.HasValue && SystemClockMhz.Value > 0)
            return SystemClockMhz.Value;
        if (MaxPllOutputMhz.HasValue && MaxPllOutputMhz.Value > 0)
        {
            var m = MaxPllOutputMhz.Value;
            // Boards commonly expose a 50–100 MHz oscillator even when the
            // PLL can synthesize much higher internally. Cap the default so
            // the sim tick count stays tractable; the Run bar's override
            // still lets students push past this ceiling when they need it.
            if (m <= 100) return m;
            return 100;
        }
        return 50;
    }
}
